// Generates derived content files from the hand-written ones:
//   content/<module>/cards.json      one flashcard per node claim
//   content/<module>/excerpts.md     every quoted passage grouped by source (what reviewers read)
// Run: node scripts/build-content.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const sources = JSON.parse(readFileSync('content/sources/index.json', 'utf8'));
const byId = Object.fromEntries(sources.map((s) => [s.id, s]));
const plain = (t) => t.replace(/\[\[([^\]|]+)(\|[^\]]+)?\]\]/g, '$1');

for (const dir of readdirSync('content').filter((d) => /^m\d+$/.test(d))) {
  const nodes = JSON.parse(readFileSync(`content/${dir}/nodes.json`, 'utf8'));
  const cards = [];
  for (const n of nodes) {
    for (const c of n.claims) {
      if (!c.card_front) continue;
      cards.push({ id: `card-${c.id}`, node: n.id, claim: c.id, front: c.card_front, back: plain(c.text) });
    }
  }
  writeFileSync(`content/${dir}/cards.json`, JSON.stringify(cards, null, 2) + '\n');

  const glossary = existsSync(`content/${dir}/glossary.json`) ? JSON.parse(readFileSync(`content/${dir}/glossary.json`, 'utf8')) : [];
  const all = [
    ...nodes.flatMap((n) => n.claims.map((c) => ({ owner: `node ${n.id}`, c }))),
    ...glossary.flatMap((g) => g.claims.map((c) => ({ owner: `glossary "${g.term}"`, c })))
  ];
  const grouped = {};
  for (const { owner, c } of all) {
    for (const s of c.sources) (grouped[s.ref] ||= []).push(`- **${c.id}** (${owner}): "${s.passage}"`);
  }
  let md = `# Source excerpts: ${dir}\n\nEvery passage the content relies on, grouped by source. Generated by scripts/build-content.mjs.\n`;
  for (const [ref, lines] of Object.entries(grouped)) {
    const s = byId[ref];
    md += `\n## ${ref}: ${s ? s.title : 'MISSING SOURCE'}\n${s ? `${s.url} (accessed ${s.accessed})` : ''}\n\n${[...new Set(lines)].join('\n')}\n`;
  }
  writeFileSync(`content/${dir}/excerpts.md`, md);
  console.log(dir, 'cards', cards.length, 'claims', all.length);
}
